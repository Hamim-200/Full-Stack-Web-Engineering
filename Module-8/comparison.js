/**
 * 1. greater than: >
 * 2. less than: <
 * 3. equal: ==, ===
 * 
 * 4. greater than or equal: >=
 * 5. less than or equal : <=
 * 6. not equal: !=, !==
 * 
 * 7. and : &&
 * 8. or : ||
*/

const a = 10;
const b = 7;

console.log(a > b); // true
console.log(a < b);//false
console.log(a === b);//false
console.log(a >= b);// true
console.log(a <= b);//false
console.log(a !== b);// true